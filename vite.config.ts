import { createHash } from "node:crypto";
import { readdirSync } from "node:fs";
import { join } from "node:path";
import { defineConfig, type Plugin } from "vite";
import react from "@vitejs/plugin-react";

// Writes sw.js next to the built site. It lists every built file so the phone
// saves the whole app on first open and keeps working with no signal.
function offlineServiceWorker(): Plugin {
  return {
    name: "offline-service-worker",
    apply: "build",
    generateBundle(_options, bundle) {
      const publicFiles = readdirSync(join(process.cwd(), "public")).filter((name) => !name.startsWith("."));
      const files = ["./", ...Object.keys(bundle).map((name) => `./${name}`), ...publicFiles.map((name) => `./${name}`)]
        .filter((name, index, all) => all.indexOf(name) === index)
        .sort();
      const version = createHash("sha256").update(files.join("\n")).digest("hex").slice(0, 12);
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: swTemplate.replace("__VERSION__", version).replace("__FILES__", JSON.stringify(files, null, 2)),
      });
    },
  };
}

const swTemplate = `// Generated by vite.config.ts. Saves the drive plan on the phone for use with no signal.
const VERSION = "__VERSION__";
const APP_CACHE = "drive-app-" + VERSION;
const FONT_CACHE = "drive-fonts-v1";
const FILES = __FILES__;
const FONT_CSS =
  "https://fonts.googleapis.com/css2?family=IBM+Plex+Mono:wght@400;500&family=Literata:opsz,wght@7..72,400;7..72,600&family=Newsreader:opsz,wght@6..72,500;6..72,650&display=swap";

async function saveFonts() {
  const cache = await caches.open(FONT_CACHE);
  const response = await fetch(FONT_CSS);
  if (!response.ok) return;
  const css = await response.clone().text();
  await cache.put(FONT_CSS, response);
  const urls = [...css.matchAll(/url\\((https:[^)]+)\\)/g)].map((match) => match[1]);
  await Promise.all(
    urls.map(async (url) => {
      if (await cache.match(url)) return;
      const font = await fetch(url);
      if (font.ok) await cache.put(url, font);
    }),
  );
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(APP_CACHE);
      await cache.addAll(FILES);
      try {
        await saveFonts();
      } catch {
        // Fonts are a nicety. The app falls back to system fonts.
      }
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(
        names.filter((name) => name !== APP_CACHE && name !== FONT_CACHE).map((name) => caches.delete(name)),
      );
      await self.clients.claim();
    })(),
  );
});

async function fromNetworkThenCache(request) {
  const cache = await caches.open(APP_CACHE);
  try {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), 4000);
    const response = await fetch(request, { signal: controller.signal });
    clearTimeout(timer);
    if (response.ok) await cache.put("./", response.clone());
    return response;
  } catch {
    return (await cache.match("./")) || (await cache.match("./index.html")) || Response.error();
  }
}

async function fromCacheThenNetwork(request, cacheName) {
  const cache = await caches.open(cacheName);
  const hit = await cache.match(request, { ignoreSearch: cacheName === APP_CACHE });
  if (hit) return hit;
  const response = await fetch(request);
  if (response.ok || response.type === "opaque") await cache.put(request, response.clone());
  return response;
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (request.mode === "navigate" && url.origin === self.location.origin) {
    event.respondWith(fromNetworkThenCache(request));
    return;
  }
  if (url.origin === self.location.origin) {
    event.respondWith(fromCacheThenNetwork(request, APP_CACHE));
    return;
  }
  if (url.hostname === "fonts.googleapis.com" || url.hostname === "fonts.gstatic.com") {
    event.respondWith(fromCacheThenNetwork(request, FONT_CACHE));
  }
});
`;

export default defineConfig({
  // Relative paths, so the same build works at a site root or under a subfolder.
  base: "./",
  plugins: [react(), offlineServiceWorker()],
  server: {
    port: 3003,
    strictPort: true,
  },
  preview: {
    port: 3003,
    strictPort: true,
    host: "127.0.0.1",
  },
});
